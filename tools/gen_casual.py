def casual_sheets():
    """回傳 {'top': Img, 'bottom': Img, 'shoes': Img}（832×1856，只填走路列；右＝左的鏡像）。"""
    out = {n: Img(gs.SHEET_W, gs.SHEET_H) for n in ('top', 'bottom', 'shoes')}
    for d, row in gs.WALK_ROW.items():
        kind = ROW['left' if d == 'right' else d]
        for step, cols in WALK_COLS.items():
            for nm, (x0, y0, rows), pal, off in (
                    ('top', TOP[(kind, step)], TOP_PAL, 0),
                    ('bottom', BOTTOM[(kind, step)], BOTTOM_PAL, 0),
                    ('shoes', SHOES[(kind, step)], dict(zip(CH, PAL)), 16)):
                for yy, line in enumerate(rows):
                    for xx, ch in enumerate(line):
                        if ch == '.':
                            continue
                        px = x0 + xx + off
                        if d == 'right':
                            px = 63 - px
                        for col in cols:
                            out[nm].px[row * gs.CELL + y0 + yy][col * gs.CELL + px] = pal[ch]
    return out
