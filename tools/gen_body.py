def _put(img, row, col, x0, y0, rows, pal, mirror):
    """把一塊字母地圖畫到 sheet 的（row, col）格；mirror＝True＝左右鏡像（x' ＝ 63 − x）。"""
    for yy, line in enumerate(rows):
        for xx, ch in enumerate(line):
            if ch == '.':
                continue
            x = x0 + xx
            x = gs.CELL - 1 - x if mirror else x
            img.px[row * gs.CELL + y0 + yy][col * gs.CELL + x] = pal[ch]


def body_sheets():
    """{'body': Img, 'face': Img}：832×1856 的 sheet，只填走路列 8～11（上／左／下／右）。"""
    out = {'body': Img(gs.SHEET_W, gs.SHEET_H), 'face': Img(gs.SHEET_W, gs.SHEET_H), 'bodyz': Img(gs.SHEET_W, gs.SHEET_H)}
    src = {'down': ('front', False), 'up': ('back', False), 'left': ('left', False), 'right': ('left', True)}
    for d, row in gs.WALK_ROW.items():
        kind, mirror = src[d]
        for col, st in enumerate(gs.WALK_FRAMES):
            for nm, pal in (('body', BODY_PAL), ('face', FACE_PAL), ('bodyz', BODY_PAL)):
                ent = SLEEP.get((kind, st)) if nm == 'bodyz' else None
                ent = ent or DATA[(kind, st)].get('body' if nm == 'bodyz' else nm)   # bodyz：待機格用閉眼版，其他格＝body
                if ent:
                    _put(out[nm], row, col, ent[0], ent[1], ent[2], pal, mirror)
    return out


def apply(sheets):
    """就地把 sheets 的 body／face 兩層換成素體（build_sheets 最後呼叫）。"""
    new = body_sheets()
    sheets['body'], sheets['face'], sheets['bodyz'] = new['body'], new['face'], new['bodyz']


def main():
    """除錯用：輸出預覽（素體、素體＋男式西裝；四個方向×步 A／待機／步 B）到指定資料夾。"""
    import gen_male
    outdir = sys.argv[1] if len(sys.argv) > 1 else 'body_out'
    os.makedirs(outdir, exist_ok=True)
    bs = body_sheets()
    male = gen_male.male_sheets()
    variants = [('素體', []), ('男式西裝', [male])]
    cols = (1, 0, 5, 3)            # 步 1（步 A）、待機、步 2（步 B）、待機
    prev = Img(len(variants) * 4 * 66, 4 * 66)
    for vi, (_, extra) in enumerate(variants):
        for di, row in enumerate((10, 9, 8, 11)):
            for ci, col in enumerate(cols):
                ox, oy = (vi * 4 + ci) * 66 + 1, di * 66 + 1
                for layer in ('body', 'bottom', 'shoes', 'top', 'face'):
                    srcs = [bs[layer]] if layer in bs else [e[layer] for e in extra if layer in e]
                    for img in srcs:
                        for y in range(gs.CELL):
                            for x in range(gs.CELL):
                                c = img.px[row * gs.CELL + y][col * gs.CELL + x]
                                if c is not None:
                                    prev.px[oy + y][ox + x] = c
    write_png(os.path.join(outdir, 'body_v2_check.png'), prev, 3, bg=(205, 235, 205))
    print('ok', outdir)


